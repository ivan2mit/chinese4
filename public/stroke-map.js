import { strokeNames } from "./acjk.js";

// Соответствие «название черты из acjk» → «базовая черта из 38».
//
// Это та же таблица, что лежит в `tools/stroke-mapping.json`: педагог заполнил
// её руками в `tools/stroke-mapping.html`. Здесь она живёт потому, что
// `tools/` не попадает в сборку, а редактору нужно соответствие в браузере.
// `test/stroke-map.test.mjs` сверяет эту копию с оригиналом, чтобы они не
// разошлись.
//
// Ключ — символ, до которого доходит рекурсивное разложение `acjk`
// (все 30 листьев одиночные). Значение — символ из `extras.sets.stroke`.
// Одна базовая черта может достаться нескольким названиям: 乀 и ㇏ — это одна
// и та же 捺, 𠃊 и ㇄ — одна 竖折.
export const STROKE_NAME_TO_BASE = Object.freeze({
  "一": "㇐",
  "丿": "㇓",
  "丨": "㇑",
  "丶": "㇔",
  "㇏": "㇏",
  "𠃌": "㇆",
  "𠃍": "㇕",
  "亅": "㇚",
  "㇇": "㇇",
  "㇀": "㇀",
  "𠃋": "㇜",
  "乛": "㇖",
  "𠄌": "㇙",
  "㇅": "㇅",
  "𠃊": "㇗",
  "㇄": "㇗",
  "乚": "㇟",
  "𡿨": "㇛",
  "㇉": "㇉",
  "㇌": "㇌",
  "⺄": "㇈",
  "㇂": "㇂",
  "㇁": "㇁",
  "乙": "㇠",
  "𠄎": "㇡",
  "㇋": "㇋",
  "㇞": "㇞",
  "㇈": "㇤",
  "乀": "㇏"
});

// Код базовой черты по названию из `acjk`. Если название само уже является
// базовой чертой из 38 (например ㇡ в 爱), оно отвечает само за себя —
// такие случаи в таблице не перечислены.
export function baseCodeFor(name, baseCodes) {
  const own = name.codePointAt(0);
  if (baseCodes.has(own)) return own;
  const base = STROKE_NAME_TO_BASE[name];
  return base ? base.codePointAt(0) : null;
}

// Декодирует иероглиф в список базовых черт по порядку построения: элемент i
// отвечает за черту i+1 в SVG, поэтому список равен `medianCount`.
//
// Возвращает ровно столько же элементов, сколько черт в глифе. `null` означает
// «опознать не удалось» — такую черту педагог называет вручную. Разложение
// упирается в 30 листьев, и все они покрыты таблицей, но на 1201 иероглифе HSK
// остаётся 158 черт (1,6%), где разложение не доходит до листа и подставляет
// примитиву (см. примечание в `tools/stroke-mapping.json`).
export function decodeStrokes(acjk, resolve, baseCodes) {
  if (!acjk) return [];
  return strokeNames(acjk, resolve).map((name) => baseCodeFor(name, baseCodes));
}